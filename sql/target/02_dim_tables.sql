CREATE SCHEMA IF NOT EXISTS dwh;

CREATE TABLE IF NOT EXISTS dwh.dim_location (
    location_key INT GENERATED BY DEFAULT AS IDENTITY,
    city_name    VARCHAR(100),
    state_code   VARCHAR(10)
);

CREATE TABLE IF NOT EXISTS dwh.dim_customer (
    customer_key       INT GENERATED BY DEFAULT AS IDENTITY,
    customer_unique_id VARCHAR(32),
    location_key       INT,
    valid_from         TIMESTAMP,
    valid_to           TIMESTAMP,
    is_current         BOOLEAN DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS dwh.dim_seller (
    seller_key   INT GENERATED BY DEFAULT AS IDENTITY,
    seller_id    VARCHAR(32),
    location_key INT
);

CREATE TABLE IF NOT EXISTS dwh.dim_product (
    product_key           INT GENERATED BY DEFAULT AS IDENTITY,
    product_id            VARCHAR(32),
    product_category_name VARCHAR(100),
    weight_kg             NUMERIC(10, 3),
    volume_m3             NUMERIC(10, 6)
);

CREATE TABLE IF NOT EXISTS dwh.dim_date (
    date_key         INT,
    full_date        DATE,
    year             INT,
    quarter          INT,
    month            INT,
    month_name       VARCHAR(20),
    day_of_week_name VARCHAR(20),
    is_weekend       BOOLEAN
);
