CREATE SCHEMA IF NOT EXISTS dwh;

CREATE TABLE IF NOT EXISTS dwh.fact_orders (
    order_key             BIGINT GENERATED BY DEFAULT AS IDENTITY,
    order_id              VARCHAR(32),
    customer_key          INT,
    shipping_location_key INT,
    purchase_date_key     INT,
    approved_date_key     INT,
    delivered_date_key    INT,
    order_status          VARCHAR(20),
    payment_type          VARCHAR(30),
    delivery_status       VARCHAR(30),
    total_items_count     INT,
    total_items_amount    NUMERIC(12, 2),
    total_freight_amount  NUMERIC(12, 2),
    total_order_amount    NUMERIC(12, 2),
    total_payment_value   NUMERIC(12, 2),
    review_score          INT
);

CREATE TABLE IF NOT EXISTS dwh.fact_sales (
    sales_key             BIGINT GENERATED BY DEFAULT AS IDENTITY,
    order_id              VARCHAR(32),
    order_item_id         INT,
    customer_key          INT,
    product_key           INT,
    seller_key            INT,
    shipping_location_key INT,
    purchase_date_key     INT,
    item_price            NUMERIC(10, 2),
    freight_value         NUMERIC(10, 2),
    total_item_amount     NUMERIC(12, 2)
);
